/* Build scoped light-color adapters for legacy CSS. No geometry changes or image filters.
 * Semantic palette overrides live in public/theme/theme.css; dark styles stay untouched.
 */
const fs = require('node:fs');
const path = require('node:path');
const postcss = require('postcss');
const root = path.join(__dirname, '..');
function tone(channels, role) {
  const [r,g,b] = channels;
  const brightness = .2126*r + .7152*g + .0722*b;
  const saturation = Math.max(r,g,b)-Math.min(r,g,b);
  if (saturation < 42) {
    const gray = role === 'background' ? Math.max(204, Math.round(255-brightness*.5))
      : role === 'border' ? Math.max(145, Math.round(240-brightness*.35))
      : Math.max(35, Math.min(105, Math.round(255-brightness*.98)));
    return [gray,gray,gray];
  }
  if (role === 'background') return channels.map(v=>Math.round(255*.86+v*.14));
  const target = role === 'border' ? 130 : 92;
  const factor = Math.min(1, target/Math.max(1,brightness));
  return channels.map(v=>Math.round(v*factor));
}
function roleFor(prop, selector) {
  if (/background|--.*(?:bg|surface|panel|menu|selection|row-background)/i.test(prop) && !/border|foreground|color$/.test(prop.replace('background-color','background'))) return 'background';
  if (/background/.test(prop)) return 'background';
  if (/border|outline|separator|divider|--grid/.test(prop)) return 'border';
  // SVG uses fill for both shapes and text. Classifying all non-label fills as
  // backgrounds washed out instance names, values, metadata and glyphs.
  if (prop==='fill' && /(?:box|head(?!er-rule)|plate|frame|badge|viewport)(?:[\s.:,#]|$)/.test(selector)) return 'background';
  return 'foreground';
}
function convert(value, role) {
  // Preserve URLs (including SVG images); transform only actual CSS color tokens.
  const urls=[];
  let text=value.replace(/url\([^)]*\)/g,url=>`__URL_${urls.push(url)-1}__`);
  text=text.replace(/#[\da-f]{3,8}\b|rgba?\([\d.,\s]+\)/gi, token=>{
    let channels,alpha;
    if(token[0]==='#') {
      let hex=token.slice(1); if(hex.length===3 || hex.length===4) hex=[...hex].map(v=>v+v).join('');
      if(hex.length!==6 && hex.length!==8) return token;
      channels=[0,2,4].map(i=>parseInt(hex.slice(i,i+2),16));
      if(hex.length===8) alpha=+(parseInt(hex.slice(6),16)/255).toFixed(3);
    } else { const parts=token.match(/[\d.]+/g).map(Number); channels=parts.slice(0,3); alpha=parts[3]; }
    // Transparent light overlays become neutral dark overlays on a light surface.
    if(alpha!==undefined) {
      if(alpha===0) return token;
      if(role==='background' && alpha>=.35) channels=tone(channels,'background');
      else if(Math.max(...channels)-Math.min(...channels)<42) channels=[0,0,0];
      else channels=tone(channels,'foreground');
      return `rgba(${channels.join(', ')}, ${alpha})`;
    }
    return '#'+tone(channels,role).map(v=>v.toString(16).padStart(2,'0')).join('');
  });
  return text.replace(/__URL_(\d+)__/g,(_,i)=>urls[Number(i)]);
}
const groups = {
  workbench:['src/renderer/styles.css','public/legacy/ui.css'],
  editor:['public/legacy/workflow-editor.css','public/legacy/ui.css','public/legacy/inspector.css','public/legacy/child-order-dnd.css'],
  log:['public/legacy/ui.css','public/runtime-log/run-log.css'],
};
function generate(files) {
  const output=postcss.root();
  for(const filename of files) {
    const source=postcss.parse(fs.readFileSync(path.join(root,filename),'utf8'));
    function walk(container,target) {
      for(const node of container.nodes || []) {
        if(node.type==='atrule') {
          if(node.name==='layer') walk(node,target);
          else if(['media','container','supports'].includes(node.name)) {
            const group=postcss.atRule({name:node.name,params:node.params}); walk(node,group); if(group.nodes?.length) target.append(group);
          }
        } else if(node.type==='rule') {
          const selector=node.selectors.map(s=>s.includes(':root') ? s.replace(':root',':root[data-theme="light"]') : `:root[data-theme="light"] ${s}`).join(', ');
          const rule=postcss.rule({selector});
          node.walkDecls(decl=>{
            if(!/color|background|border|outline|fill|stroke|^--/.test(decl.prop) || /shadow|image-rendering/.test(decl.prop)) return;
            const value=convert(decl.value,roleFor(decl.prop,node.selector));
            if(value!==decl.value) rule.append({prop:decl.prop,value,important:decl.important});
          });
          if(rule.nodes?.length) target.append(rule);
        }
      }
    }
    walk(source,output);
  }
  return '/* Generated by scripts/build-light-palette.cjs. Edit semantic overrides in theme.css. */\n'+output.toString()+'\n';
}
if(require.main===module) {
  for(const [group,files] of Object.entries(groups)) {
    const filename=path.join(root,`public/theme/${group}-light.css`);
    const css=generate(files);
    if(process.argv.includes('--check')) {
      if(!fs.existsSync(filename) || fs.readFileSync(filename,'utf8')!==css) throw new Error(`Stale palette: ${filename}`);
    } else fs.writeFileSync(filename,css);
  }
}
module.exports={tone,convert,generate,groups};
