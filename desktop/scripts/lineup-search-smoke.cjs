// Exercise real renderer DOM with offline restriction/refresh fixtures.
const { app, BrowserWindow } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const root = path.resolve(__dirname, '..');
const artifacts = path.resolve(root, '../artifacts/lineup-search-smoke');
app.disableHardwareAcceleration();
app.commandLine.appendSwitch('in-process-gpu');
app.setPath('userData', path.join(artifacts, 'user-data'));
app.on('window-all-closed', () => {});

app.whenReady().then(async () => {
  fs.mkdirSync(artifacts, { recursive: true });
  const css = fs.readFileSync(path.join(root, 'src/renderer/styles.css'), 'utf8').replace(/^@import[^;]*;/, '');
  const palette = ['workbench-light.css', 'theme.css'].map(name => fs.readFileSync(path.join(root, 'public/theme', name), 'utf8')).join('\n');
  const html = path.join(artifacts, 'preview.html');
  fs.writeFileSync(html, `<!doctype html><html lang="zh-CN" data-theme="dark"><meta charset="UTF-8"><link rel="stylesheet" href="${pathToFileURL(path.join(root, 'public/fonts/harmonyos-sans-sc/Regular.css')).href}"><style>${css}\n${palette}\nhtml,body{margin:0;width:100%;height:100%;overflow:hidden}#root{height:100%;box-sizing:border-box}</style><body><div id="root" class="lineup-browser"></div></body></html>`);
  const createWindow = (width, height) => new BrowserWindow({ show: false, width, height, webPreferences: { nodeIntegration: true, contextIsolation: false, sandbox: false, offscreen: true } });
  let win = createWindow(1360, 760);
  await win.loadFile(html);
  const renderer = path.join(root, 'dist-test-renderer/renderer/lineup-browser.js');
  const setup = `window.install=require(${JSON.stringify(renderer)}).installLineupBrowser;
    window.sources=['bilibili','netease-community','netease-official','weibo','nga'];
    window.failure={results:[],unavailableSources:sources,sourceErrors:sources.map(source=>({source,message:source==='bilibili'?'搜索请求被站点限制（HTTP 412），可点“B站”在网页中搜索。':'Bing：未返回可用的目标站点链接；百度：需要网页安全验证，请使用来源入口'}))};
    window.guide={bvid:'BV1234567890',source:'bilibili',url:'https://www.bilibili.com/video/BV1234567890/',title:'御魂副本通关攻略（界面测试）',author:'攻略作者',description:'原先已获取的攻略在刷新失败后继续显示。',publishedAt:1780000000,duration:'03:20',views:3200,favorites:100};
    window.opened=[];window.store={};
    window.api={searchLineups:async()=>failure,readLayout:key=>store[key]??null,writeLayout:(key,value)=>store[key]=value,openLineupSource:async(...args)=>opened.push(args),openLineupPost:async()=>{},openLineupUrl:async()=>{}};
    window.browser=install(document.getElementById('root'),api);browser.load();`;
  await win.webContents.executeJavaScript(setup);
  const state = () => win.webContents.executeJavaScript(`({errors:document.querySelector('[data-lineup="errors"]').children.length,cards:document.querySelectorAll('.lineup-card').length,status:document.querySelector('[data-lineup="status"]').textContent,overflow:document.getElementById('root').scrollWidth>document.getElementById('root').clientWidth})`);
  let first = await state();
  assert.equal(first.errors, 5); assert.equal(first.cards, 0); assert.equal(first.overflow, false);
  fs.writeFileSync(path.join(artifacts, 'all-failed.png'), (await win.webContents.capturePage()).toPNG());
  await win.webContents.executeJavaScript(`browser.dispose();store={'onmyoji-studio.lineup-search-cache.v4':JSON.stringify({[JSON.stringify(['阴阳师 御魂阵容','pubdate'])]:{results:[guide],unavailableSources:[],cachedAt:Date.now()-5000}})};browser=install(document.getElementById('root'),api);browser.load();document.querySelector('[data-lineup="refresh"]').click();`);
  const retained = await state();
  assert.equal(retained.cards, 1); assert.match(retained.status, /保留了哔哩哔哩/);
  fs.writeFileSync(path.join(artifacts, 'retained-guides.png'), (await win.webContents.capturePage()).toPNG());
  win.destroy();
  win = createWindow(560, 680);
  await win.loadFile(html);
  await win.webContents.executeJavaScript(setup);
  const narrow = await state();
  assert.equal(narrow.overflow, false);
  fs.writeFileSync(path.join(artifacts, 'narrow.png'), (await win.webContents.capturePage()).toPNG());
  await win.webContents.executeJavaScript(`document.querySelector('[data-lineup="errors"] button').click()`);
  assert.equal(await win.webContents.executeJavaScript(`opened[0][0]`), 'bilibili');
  await win.webContents.executeJavaScript(`browser.dispose();store={};api.searchLineups=async()=>({results:[{...guide,bvid:'SRCH-00000001',source:'nga',url:'https://bbs.nga.cn/read.php?tid=123',title:'魂土低配阵容攻略（界面测试）',replies:28}],unavailableSources:[]});browser=install(document.getElementById('root'),api);browser.load();`);
  const nga = await state();
  assert.equal(nga.cards, 1); assert.equal(nga.errors, 0); assert.equal(nga.overflow, false);
  assert.match(await win.webContents.executeJavaScript(`document.querySelector('.lineup-metrics').textContent`), /NGA 阴阳师版块.*回复 28/);
  await win.webContents.executeJavaScript(`document.querySelector('[data-source="nga"]').click()`);
  assert.equal(await win.webContents.executeJavaScript(`opened[1][0]`), 'nga');
  fs.writeFileSync(path.join(artifacts, 'nga-guide.png'), (await win.webContents.capturePage()).toPNG());
  fs.writeFileSync(path.join(artifacts, 'report.json'), JSON.stringify({ first, retained, narrow, nga }, null, 2));
  console.log(JSON.stringify({ first, retained, narrow, nga }, null, 2));
  win.destroy(); app.quit();
}).catch(error => { console.error(error); app.exit(1); });
